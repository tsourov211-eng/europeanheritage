export function getCollection(slug: string): CollectionData {
  if (collectionsCatalog[slug]) {
    return collectionsCatalog[slug];
  }

  // Fallback to a normalized title
  const formattedTitle = slug
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');

  return {
    slug,
    title: formattedTitle,
    subtitle: 'Considered Surfaces & Architectural Ceramics',
    description: `Explore our curated selection of ${formattedTitle.toLowerCase()}. Selected for exceptional durability, tactile glazes, and timeless character across considered British homes.`,
    heroImage: 'https://images.pexels.com/photos/8134805/pexels-photo-8134805.jpeg?auto=compress&cs=tinysrgb&h=1600&w=2400',
    colorTags: ['All', 'White', 'Beige', 'Grey', 'Blue'],
    products: collectionsCatalog['porcelain-tiles'].products,
  };
}

export function getAllProducts(): { product: Product; collectionSlug: string }[] {
  const seen = new Set<string>();
  const list: { product: Product; collectionSlug: string }[] = [];

  Object.values(collectionsCatalog).forEach((col) => {
    col.products.forEach((p) => {
      if (!seen.has(p.id)) {
        seen.add(p.id);
        list.push({ product: p, collectionSlug: col.slug });
      }
    });
  });

  return list;
}

